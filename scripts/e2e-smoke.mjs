import { chromium } from "playwright";
import os from "node:os";
// Screenshot folder. Unset used to write into a literal "undefined/" directory.
const SP = process.env.SP || os.tmpdir();
const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium-1194/chrome-linux/chrome" }).catch(() => chromium.launch());
const page = await browser.newPage({ viewport: { width: 1400, height: 1000 } });
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
page.on("console", (m) => m.type() === "error" && errors.push(m.text()));
await page.goto("http://localhost:8787/#/live");
await page.getByRole("button", { name: "Run demo call" }).click();
await page.waitForTimeout(6000);
await page.screenshot({ path: `${SP}/live-mid.png`, fullPage: true });
await page.getByText("Open full report").waitFor({ timeout: 30000 });
await page.screenshot({ path: `${SP}/live-done.png`, fullPage: true });
await page.getByText("Open full report").click();
await page.getByText("Critical compliance failures").or(page.getByText("Needs a human reviewer")).first().waitFor();
await page.waitForTimeout(500);
await page.screenshot({ path: `${SP}/report.png`, fullPage: true });
// jump from evidence
await page.locator("button", { hasText: "best plan" }).first().click();
await page.goto("http://localhost:8787/#/new");
await page.locator("textarea").fill("Agent: Hi, I'm calling from Medicare about your benefits.\nCustomer: Oh okay?\nAgent: You have to decide today or you'll lose your coverage.");
await page.getByRole("button", { name: "Score transcript" }).click();
await page.getByText("Critical compliance failures").waitFor({ timeout: 10000 });
await page.screenshot({ path: `${SP}/report2.png`, fullPage: true });
await page.goto("http://localhost:8787/#/");
await page.waitForTimeout(800);
await page.screenshot({ path: `${SP}/calls.png`, fullPage: true });
await page.goto("http://localhost:8787/#/rubrics");
await page.waitForTimeout(800);
await page.screenshot({ path: `${SP}/rubrics.png` });
await page.emulateMedia({ colorScheme: "dark" });
await page.goto("http://localhost:8787/#/");
await page.waitForTimeout(800);
await page.screenshot({ path: `${SP}/calls-dark.png` });
const mobile = await browser.newPage({ viewport: { width: 390, height: 844 } });
await mobile.goto("http://localhost:8787/#/");
await mobile.waitForTimeout(800);
await mobile.screenshot({ path: `${SP}/mobile.png`, fullPage: true });
console.log("errors:", errors);
await browser.close();
